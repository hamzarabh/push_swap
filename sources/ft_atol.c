long	ft_atol(char *a_num)
{
	int		i;
	long	res;
	int		sign;

	sign = 1;
	i = 0;
	res = 0;
	if (a_num[i] == '-')
	{
		sign = -1;
		i++;
	}
	if (a_num[i] == '+')
		i++;
	while (a_num[i])
	{
		res = (res * 10) + (a_num[i] - '0');
		i++;
	}
	return (res * sign);
}
